import test from "node:test";
import assert from "node:assert/strict";
import { existsSync, globSync, readFileSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const doc = readFileSync(join(root, "botd/DEMO.md"), "utf8");

// Only repository-rooted paths are inputs; .tmp paths are produced by the demo.
function repoPaths(text: string): string[] {
  return [...new Set([...text.matchAll(/(?<![\w./$-])(?:botd|client-ui|scripts|probes|tools)\/[\w./*-]+/g)]
    .map((match) => match[0])
    .filter((path) => !path.startsWith("botd/.tmp/")))].sort();
}

function missingPaths(paths: string[]): string[] {
  return paths.filter((path) => /[*?[]/.test(path)
    ? globSync(path, { cwd: root }).length === 0
    : !existsSync(join(root, path)));
}

function nodeFiles(text: string): string[] {
  const files: string[] = [];
  for (const match of text.matchAll(/(?:^\s*|`)node\s+([^`\n]+)/gm)) {
    const args = match[1].match(/"[^"]*"|'[^']*'|\S+/g) ?? [];
    if (args.includes("-e")) continue;
    for (const arg of args) {
      if (arg.startsWith("-")) continue;
      const path = arg.replace(/^['"]|['"]$/g, "");
      if (path.startsWith("<prefix>/")) break; // installed launcher, generated by installer
      files.push(path);
      if (!args.includes("--test")) break;
    }
  }
  return [...new Set(files)].sort();
}

function variables(text: string): string[] {
  const names = [...text.matchAll(/\$([A-Z][A-Z_0-9]*)\b|`(BOTD_[A-Z_0-9]+)`/g)]
    .map((match) => match[1] ?? match[2]);
  return [...new Set(names)].sort();
}

function sourceFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? sourceFiles(path) : entry.isFile() ? [path] : [];
  });
}

function missingVariables(names: string[], sources: string): string[] {
  const tokens = new Set(sources.match(/\b[A-Z][A-Z_0-9]*\b/g) ?? []);
  return names.filter((name) => !tokens.has(name));
}

// Exact token sequences, including the runbook's concrete host wording.
const forbidden = [
  ["claude", "runs", "on", "a", "remote", "host"],
  ["claude", "code", "on", "<host-a>"],
  ["on", "<host-a>", "the", "claude", "cli"],
  ["codex", "runs", "on", "the", "local", "machine"],
  ["pi", "runs", "on", "the", "local", "machine"],
];
function contradictions(text: string): string[] {
  return text.split("\n").filter((line) => {
    const words = line.toLowerCase().match(/<[^>]+>|[a-z0-9-]+/g) ?? [];
    if (words.includes("not") || words.includes("never") || words.includes("no")) return false;
    return forbidden.filter((phrase) => words.filter((_, index) =>
      phrase.every((word, offset) => words[index + offset] === word)).length > 0).length > 0;
  });
}

test("repository paths in the runbook exist", () => {
  assert.deepEqual(repoPaths("`botd/src/main.ts` `botd/.tmp/demo`"), ["botd/src/main.ts"]);
  assert.deepEqual(missingPaths(repoPaths("`botd/src/missing-synthetic.ts`")), ["botd/src/missing-synthetic.ts"]);
  assert.deepEqual(missingPaths(repoPaths(doc)), []);
});

test("node command file operands exist", () => {
  assert.deepEqual(nodeFiles('node --test "botd/test/*.test.ts"\nnode --input-type=module -e \'code\''), ["botd/test/*.test.ts"]);
  assert.deepEqual(missingPaths(nodeFiles("node tools/missing-synthetic.mjs")), ["tools/missing-synthetic.mjs"]);
  assert.deepEqual(missingPaths(nodeFiles(doc)), []);
});

test("documented environment variables occur in source or scripts", () => {
  const sources = ["botd/src", "botd/demo", "scripts"].flatMap((dir) => sourceFiles(join(root, dir)))
    .map((path) => readFileSync(path, "utf8")).join("\n");
  assert.deepEqual(variables("$HOME `BOTD_HOME`"), ["BOTD_HOME", "HOME"]);
  assert.deepEqual(missingVariables(["SYNTHETIC_MISSING"], sources), ["SYNTHETIC_MISSING"]);
  assert.deepEqual(missingVariables(variables(doc), sources), []);
});

test("runbook does not contradict the host policy", () => {
  assert.deepEqual(contradictions("Claude runs on a remote host"), ["Claude runs on a remote host"]);
  assert.deepEqual(contradictions("Claude does not run on a remote host"), []);
  assert.deepEqual(contradictions("Codex runs on the local machine\nPi runs on the local machine"), ["Codex runs on the local machine", "Pi runs on the local machine"]);
  assert.deepEqual(contradictions(doc), []);
});
